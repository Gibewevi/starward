export function renderMenuPixels(root) {
  for (const element of root.querySelectorAll('[data-pixel-text]')) {
    const text = element.dataset.pixelText;
    const chars = [...text.normalize('NFD').replace(/[\u0300-\u036f]/g, '')];
    const spacing = text === 'STARWARD' ? 3 : 2;
    const canvas = document.createElement('canvas');
    canvas.width = chars.reduce((w, char) => w + (rows[char]?.[0].length ?? 3) + spacing, -spacing);
    canvas.height = 10;
    canvas.setAttribute('aria-hidden', 'true');
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = '#ffffff';
    let x = 0;
    chars.forEach((char, index) => {
      const glyph = rows[char] ?? rows[' '];
      glyph.forEach((row, y) => [...row].forEach((on, dx) => {
        if (on === '1') ctx.fillRect(x + dx, y + 3, 1, 1);
      }));
      if (text[index] === 'É') { ctx.fillRect(x + 3, 0, 1, 1); ctx.fillRect(x + 2, 1, 1, 1); }
      x += glyph[0].length + spacing;
    });
    const accessible = document.createElement('span');
    accessible.className = 'menu-sr-only';
    accessible.textContent = text;
    element.replaceChildren(accessible, canvas);
  }
}
